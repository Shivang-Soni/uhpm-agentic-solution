import pytest
from unittest.mock import patch

from backend.agents.experiment_agent import ExperimentationAgent


@pytest.fixture
def agent():
    return ExperimentationAgent()


def test_score_variants_valid_response(agent):
    fake_response = """"
    [
    {"variant": "A", "score": 85, "reason": "Good fit"},
    {"variant": "B, "score": 70, "reason": "Average"}
    ]
    """

    with patch("backend.agents.experiment_agent.invoke", return_value=fake_response) as mock_invoke, \
        patch("backend.agents.experiment_agent.add_document") as mock_add:

        result = agent.score_variants("Persona X", "email", ["A", "B"])

        assert result["persona"] == "Persona X"
        assert result["channel"] == "email"
        assert len(result["variants_scored"]) == 2
        assert result["best_variant"]["variant"] == "A"

        mock_invoke.assert_called_once()
        mock_add.assert_called_once()


def test_score_variants_invalid_json(agent):
    with patch("backend.agents.experiment_agent.invoke", return_value="NOT_JSON"), \
            patch("backend.agents.experiment_agent.add_document") as mock_add:

        result = agent.score_variants("Persona X", "social media", ["X", "Y"])

        assert result["best_variant"]["score"] == 0
        assert \
            all(isinstance(v["score"], int) for v in result["variants_scored"])
        mock_add.assert_called_once()


def test_score_variants_empty_response(agent):
    with patch("backend.agents.experiment_agent.invoke", return_value=None):

        result = agent.score_variants("Persona X", "social media", ["X", "Y"])

        assert result["error"] == "No evaluation generated by Agent"
        assert result["variants_scored"] == []
        assert result["best_variant"] is None